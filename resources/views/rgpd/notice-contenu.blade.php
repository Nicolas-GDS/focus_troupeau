<h2 class="font-titre text-lg font-semibold">Pourquoi nous traitons vos données</h2>
<p>{{ config('brand.nom') }} vous donne accès au dossier d'approche globale de la santé de votre troupeau : résultats d'analyses,
    préconisations, positionnement par rapport aux autres élevages, stocks fourragers et projections. Vos données servent à
    exécuter la convention que vous avez signée avec votre GDS.</p>

<h2 class="font-titre text-lg font-semibold">Base légale</h2>
<p>L'exécution de la convention d'approche globale ; l'intérêt légitime du GDS pour les références agrégées entre élevages,
    établies sans aucune donnée d'identification et seulement à partir de cinq lots.</p>

<h2 class="font-titre text-lg font-semibold">Qui y a accès</h2>
<p>Les techniciens et le vétérinaire conseil de votre GDS. Votre vétérinaire, seulement si vous lui en donnez l'accès ; vous pouvez
    retirer cet accès à tout moment depuis « Mes consentements ». Aucune donnée n'est transférée hors de l'Union européenne.</p>

<h2 class="font-titre text-lg font-semibold">Combien de temps</h2>
<p>Les données de la convention et du dossier sont conservées dix ans après la fin de la convention ; les journaux de connexion
    douze mois ; les notifications vingt-quatre mois. <span class="font-sans text-sm text-etat-alerte">[Durées à confirmer avec le registre des traitements du GDS.]</span></p>

<h2 class="font-titre text-lg font-semibold">Vos droits</h2>
<p>Vous pouvez accéder à vos données et les exporter, demander leur rectification à votre technicien, demander leur effacement,
    et retirer à tout moment votre accord à l'utilisation de vos lots dans les références ou au partage avec votre vétérinaire.
    Pour exercer ces droits, contactez votre GDS.</p>
